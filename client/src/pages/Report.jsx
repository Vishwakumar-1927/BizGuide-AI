import { Navigate, useLocation } from "react-router-dom";
import jsPDF from "jspdf";
import html2canvas from "html2canvas";

import "./Report.css";

import ReportHeader from "../components/ReportHeader";
import BusinessSection from "../components/report/BusinessSection";
import ExecutiveSummary from "../components/report/ExecutiveSummary";
import MarketAnalysis from "../components/report/MarketAnalysis";
import BusinessDashboard from "../components/report/BusinessDashboard";
import FinancialAnalysis from "../components/report/FinancialAnalysis";
import SWOTAnalysis from "../components/report/SWOTAnalysis";
import RiskAssessment from "../components/report/RiskAssessment";
import Recommendations from "../components/report/Recommendations";
import FinalVerdict from "../components/report/FinalVerdict";

function Report() {
  const location = useLocation();

  if (!location.state) {
    return <Navigate to="/analyze" replace />;
  }

  const { business, report } = location.state;

  const downloadPDF = async () => {
    const input = document.getElementById("report-content");

    if (!input) return;

    try {
      const canvas = await html2canvas(input, {
        scale: 1.3,
        useCORS: true,
        backgroundColor: "#ffffff",
        scrollY: -window.scrollY,
        logging: false,
      });

      // JPEG compression significantly reduces PDF size
      const imgData = canvas.toDataURL("image/jpeg", 0.72);

      const pdf = new jsPDF("p", "mm", "a4");

      const pageWidth = 210;
      const pageHeight = 297;

      const imgWidth = pageWidth;
      const imgHeight =
        (canvas.height * imgWidth) / canvas.width;

      let heightLeft = imgHeight;
      let position = 0;

      // First page
      pdf.addImage(
        imgData,
        "JPEG",
        0,
        position,
        imgWidth,
        imgHeight,
        undefined,
        "FAST"
      );

      heightLeft -= pageHeight;

      // Remaining pages
      while (heightLeft > 0) {
        position = heightLeft - imgHeight;

        pdf.addPage();

        pdf.addImage(
          imgData,
          "JPEG",
          0,
          position,
          imgWidth,
          imgHeight,
          undefined,
          "FAST"
        );

        heightLeft -= pageHeight;
      }

      pdf.save(
        `${business.businessName || "BizGuide"}_Business_Report.pdf`
      );
    } catch (error) {
      console.error("PDF generation failed:", error);
      alert("Unable to generate PDF. Please try again.");
    }
  };

  return (
    <div className="report-page">

      {/* ========================= */}
      {/* REPORT TOOLBAR */}
      {/* ========================= */}

      <div className="report-toolbar">

        <div className="report-toolbar-info">
          <span>BUSINESS INTELLIGENCE</span>
          <strong>AI Analysis Report</strong>
        </div>

        <button
          className="download-btn"
          onClick={downloadPDF}
        >
          <span className="download-icon">↓</span>
          Download PDF Report
        </button>

      </div>

      {/* ========================= */}
      {/* REPORT DOCUMENT */}
      {/* ========================= */}

      <main id="report-content">

        <div className="report-document-header">
          <span>BIZGUIDE AI</span>
          <div className="document-line" />
          <small>BUSINESS ANALYSIS REPORT</small>
        </div>

        <ReportHeader business={business} />

        <BusinessSection business={business} />

        <ExecutiveSummary report={report} />

        <BusinessDashboard report={report} />

        <MarketAnalysis report={report} />

        <FinancialAnalysis report={report} />

        <SWOTAnalysis report={report} />

        <RiskAssessment report={report} />

        <Recommendations report={report} />

        <FinalVerdict report={report} />

        <div className="report-end">

          <div className="report-end-icon">
            ✦
          </div>

          <h3>End of Business Analysis</h3>

          <p>
            Generated by BizGuide AI using AI-powered business intelligence.
          </p>

        </div>

      </main>

    </div>
  );
}

export default Report;