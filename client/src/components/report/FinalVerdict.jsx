import "./FinalVerdict.css";
import {
  CircularProgressbar,
  buildStyles,
} from "react-circular-progressbar";
import "react-circular-progressbar/dist/styles.css";

import {
  FaCheckCircle,
  FaExclamationTriangle,
  FaTimesCircle,
  FaRobot,
  FaChartLine,
  FaArrowRight,
} from "react-icons/fa";

function FinalVerdict({ report }) {
  if (!report?.finalVerdict) return null;

  const {
    businessScore = 0,
    decision = "Not Available",
    reason = "No recommendation available.",
  } = report.finalVerdict;

  const score = Math.min(
    100,
    Math.max(0, Number(businessScore) || 0)
  );

  const getDecisionClass = () => {
    if (decision === "GO-AHEAD") return "go";

    if (decision === "PROCEED WITH CAUTION")
      return "caution";

    return "reject";
  };

  const getDecisionIcon = () => {
    if (decision === "GO-AHEAD") {
      return <FaCheckCircle />;
    }

    if (decision === "PROCEED WITH CAUTION") {
      return <FaExclamationTriangle />;
    }

    return <FaTimesCircle />;
  };

  return (
    <section className="verdict-section">

      {/* ========================= */}
      {/* FINAL VERDICT HERO */}
      {/* ========================= */}

      <div className={`verdict-hero ${getDecisionClass()}`}>

        <div className="verdict-badge">
          <FaRobot />
          <span>AI FINAL VERDICT</span>
        </div>

        <div className="verdict-main">

          {/* SCORE */}

          <div className="score-wrapper">

            <div className="final-score-circle">

              <CircularProgressbar
                value={score}
                styles={buildStyles({
                  pathColor: "#ffffff",
                  trailColor: "rgba(255,255,255,0.18)",
                  textColor: "#312e81",
                  strokeLinecap: "round",
                })}
              />

              {/* Explicit score text */}
              <div className="final-score-value">
                {score}
              </div>

            </div>

            <div className="score-label">
              <span>BUSINESS</span>
              <strong>SCORE</strong>
            </div>

          </div>

          {/* DECISION */}

          <div className="verdict-info">

            <div className="decision">

              <div className="decision-icon">
                {getDecisionIcon()}
              </div>

              <div>
                <span>RECOMMENDATION</span>

                <h2>
                  {decision}
                </h2>
              </div>

            </div>

            <p>
              {reason}
            </p>

          </div>

        </div>

      </div>


      {/* ========================= */}
      {/* SCORE BREAKDOWN */}
      {/* ========================= */}

      <div className="breakdown-card">

        <div className="section-heading">

          <div className="section-heading-icon">
            <FaChartLine />
          </div>

          <div>
            <span>SCORE ANALYTICS</span>

            <h2>
              AI Score Breakdown
            </h2>
          </div>

        </div>


        <div className="progress-item">

          <span>
            Overall Business Score
          </span>

          <strong>
            {score}%
          </strong>

        </div>


        <div className="progress-bar">

          <div
            className="progress-fill"
            style={{
              width: `${score}%`,
            }}
          />

        </div>


        <div className="score-range">

          <span>
            0 — Low Potential
          </span>

          <span>
            100 — Excellent Potential
          </span>

        </div>

      </div>


      {/* ========================= */}
      {/* AI SUMMARY */}
      {/* ========================= */}

      <div className="ai-summary">

        <div className="summary-title">

          <div className="summary-icon">
            <FaRobot />
          </div>

          <div>

            <span>
              FINAL AI INSIGHT
            </span>

            <h2>
              AI Final Recommendation
            </h2>

          </div>

        </div>


        <p>
          After analyzing market demand, competition,
          financial projections, SWOT factors, and
          business risks, BizGuide AI has reached
          the following conclusion:
        </p>


        <blockquote>

          <span className="quote-mark">
            “
          </span>

          <span>
            {reason}
          </span>

        </blockquote>


        <div className="verdict-footer">

          <span>
            Generated by BizGuide AI
          </span>

          <FaArrowRight />

        </div>

      </div>

    </section>
  );
}

export default FinalVerdict;